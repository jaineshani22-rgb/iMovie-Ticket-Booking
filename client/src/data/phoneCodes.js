export function getPhoneCodeByCountry(countryCode) {
  if (!countryCode) return PHONE_COUNTRY_CODES[0];
  const upper = countryCode.toUpperCase();
  return PHONE_COUNTRY_CODES.find((p) => p.country === upper) || PHONE_COUNTRY_CODES[0];
}

export function parsePhoneNumber(fullPhone) {
  if (!fullPhone) return { dialCode: '+91', nationalNumber: '' };
  const trimmed = fullPhone.trim();
  // Check if string starts with any known dialCode (sort longest first to avoid +1 vs +123 collisions)
  const sorted = [...PHONE_COUNTRY_CODES].sort((a, b) => b.code.length - a.code.length);
  for (const item of sorted) {
    if (trimmed.startsWith(item.code)) {
      return {
        dialCode: item.code,
        nationalNumber: trimmed.slice(item.code.length).trim()
      };
    }
  }
  return { dialCode: '+91', nationalNumber: trimmed };
}
